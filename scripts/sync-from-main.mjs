// Copies the files the site shows from the app branch into content/, and reads
// the app's own shortcut list and command palette into src/app-keys.ts.
// Never edit content/*.md or src/app-keys.ts by hand on this branch; run
// `npm run sync` (or let the release workflow on main do it) so the site and
// the app never disagree.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ref = process.argv[2] ?? "origin/main";
const show = (f) => execFileSync("git", ["show", `${ref}:${f}`], { encoding: "utf8" });

for (const f of ["CHANGELOG.md", "PRIVACY.md"]) {
  writeFileSync(new URL(`../content/${f}`, import.meta.url), show(f));
  console.log(`synced ${f} from ${ref}`);
}

// ---------------------------------------------------------------- shortcuts.rs → groups

const STR = String.raw`"((?:[^"\\]|\\.)*)"`;
const unescape = (s) => s.replace(/\\(.)/g, "$1");

const shortcutsRs = show("crates/kitab-ui/src/shortcuts.rs");
const groupsSrc = shortcutsRs.slice(shortcutsRs.indexOf("pub const GROUPS"), shortcutsRs.indexOf("/// A GPUI keystroke"));
const groups = groupsSrc
  .split("Group {")
  .slice(1)
  .map((chunk) => {
    const title = unescape(chunk.match(new RegExp(`title:\\s*${STR}`))[1]);
    const rows = [...chunk.matchAll(new RegExp(String.raw`\(\s*${STR},\s*${STR},?\s*\)`, "g"))].map((m) => [unescape(m[1]), unescape(m[2])]);
    return { title, rows };
  });
if (groups.length < 5 || groups.some((g) => !g.rows.length)) throw new Error("shortcuts.rs: could not read GROUPS");

// ---------------------------------------------------------------- palette.rs + actions.rs → commands with keys

// GPUI keystroke ("ctrl-shift-p") as people write it ("Ctrl+Shift+P"), as shortcuts.rs does.
const NAMES = { ctrl: "Ctrl", shift: "Shift", alt: "Alt", pagedown: "PgDn", pageup: "PgUp", escape: "Esc", space: "Space", enter: "Enter", tab: "Tab", left: "Left", right: "Right", up: "Up", down: "Down", home: "Home", end: "End", backspace: "Backspace", delete: "Del" };
function pretty(binding) {
  const minus = binding.endsWith("--");
  const body = minus ? binding.slice(0, -2) : binding;
  const parts = body.split("-").filter(Boolean).map((p) => NAMES[p] ?? p.toUpperCase());
  if (minus) parts.push("-");
  return parts.join("+");
}

const actionsRs = show("crates/kitab-ui/src/actions.rs");
const bindFn = actionsRs.slice(actionsRs.indexOf("pub fn bind_default_keys"));
const firstBlock = bindFn.slice(0, bindFn.indexOf("cx.bind_keys(\n        [") > 0 ? bindFn.indexOf("cx.bind_keys(\n        [") : undefined);
const keysOf = {};
for (const m of firstBlock.matchAll(new RegExp(String.raw`KeyBinding::new\(${STR},\s*(\w+),\s*([^)]*)\)`, "g"))) {
  const [, key, action, ctx] = m;
  if (!/^(w|r)$/.test(ctx.trim())) continue; // field-only keys (Enter, Esc in a bar) are not the command's key
  if (key === "ctrl-+") continue; // an alias of Ctrl+=
  (keysOf[action] ??= []).push(pretty(unescape(key)));
}

const paletteRs = show("crates/kitab-ui/src/palette.rs");
const commands = [...paletteRs.matchAll(new RegExp(String.raw`cmd!\(\s*${STR},\s*${STR},\s*${STR},\s*(true|false),\s*(\w+),?\s*\)`, "g"))].map((m) => ({
  group: unescape(m[1]),
  label: unescape(m[2]),
  doc: m[4] === "true",
  keys: keysOf[m[5]] ?? [],
}));
if (commands.length < 30) throw new Error(`palette.rs: read only ${commands.length} commands`);

const header = `// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by scripts/sync-from-main.mjs from ${ref}: crates/kitab-ui/src/shortcuts.rs,
// palette.rs and actions.rs. Do not edit; run \`npm run sync\`.
`;
writeFileSync(
  new URL("../src/app-keys.ts", import.meta.url),
  `${header}
export type KeyGroup = { title: string; rows: [string, string][] };
export type PaletteCommand = { group: string; label: string; doc: boolean; keys: string[] };

/** Every shortcut, grouped, as Settings › Shortcuts lists them. Alternatives are separated by " / ". */
export const KEY_GROUPS: KeyGroup[] = ${JSON.stringify(groups, null, 2)};

/** Every command in the command palette, in the app's order, with its default keys. */
export const PALETTE: PaletteCommand[] = ${JSON.stringify(commands, null, 2)};
`,
);
console.log(`synced ${groups.length} shortcut groups and ${commands.length} palette commands from ${ref}`);
